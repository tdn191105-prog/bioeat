# --------------------------------------------------------------------------- #
#  Транслитерация названий в слаг.
#  Используется и роутером категорий, и скриптом загрузки фотографий,
#  поэтому живёт здесь, а не в app/routers/admin.py.
# --------------------------------------------------------------------------- #
TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e", "ж": "zh",
    "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o",
    "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f", "х": "h", "ц": "c",
    "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu",
    "я": "ya", " ": "-",
}


def slugify(value: str, fallback: str = "category") -> str:
    text = "".join(TRANSLIT.get(ch, ch) for ch in value.lower())
    text = re.sub(r"[^a-z0-9-]+", "-", text).strip("-")
    return text or fallback
